import fnmatch
import subprocess
from dataclasses import asdict, dataclass
from pathlib import Path

import clones as clonelib
import graph as graphlib
import reach as reachlib
from gitlog import WINDOW_DAYS, change_history
from imports import ImportResolver
from lenses import lenses_for
from languages import language_for
from metrics import classify_lines, measure
from packing import pack
from structure import analyze, identifier_index
